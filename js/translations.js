class TranslationManager {
  constructor() {
    this.currentLang = localStorage.getItem("portfolio-lang") || "fr";
  }

  setLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem("portfolio-lang", lang);

    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === lang);
    });

    document.documentElement.lang = lang;

    this.updatePageContent(lang);

    if (typeof window.renderSiteContent === "function") {
      window.renderSiteContent();
    }

    if (window.projectsManager) {
      window.projectsManager.setLanguage(lang);

      // IMPORTANT : attendre la fin du cycle DOM
      requestAnimationFrame(() => {
        window.projectsManager.updateProjects();
      });
    }
  }

  updatePageContent(lang) {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.dataset.i18n;
      if (translations[lang] && translations[lang][key]) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = translations[lang][key];
        } else if (el.tagName === "OPTION") {
          el.textContent = translations[lang][key];
        } else {
          el.textContent = translations[lang][key];
        }
      }
    });
  }

  getCurrentLanguage() {
    return this.currentLang;
  }

  init() {
    // Événements sur les boutons de langue
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.addEventListener("click", () => this.setLanguage(btn.dataset.lang));
    });

    // Chargement initial
    this.setLanguage(this.currentLang);
  }
}

// Export pour utilisation globale
const translationManager = new TranslationManager();
