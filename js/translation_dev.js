// Gestionnaire de traductions
class TranslationManager {
  constructor() {
    this.currentLanguage = localStorage.getItem("language") || "fr";
  }

  init() {
    this.updatePageTranslations();
    this.setupLanguageToggle();
  }

  getCurrentLanguage() {
    return this.currentLanguage;
  }

  translate(key) {
    return translations[this.currentLanguage][key] || key;
  }

  updatePageTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.getAttribute("data-i18n");
      element.textContent = this.translate(key);
    });
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLanguage = lang;
      localStorage.setItem("language", lang);
      this.updatePageTranslations();

      // Notifier les gestionnaires dépendants du changement de langue
      if (typeof projectsManager !== "undefined") {
        projectsManager.setLanguage(lang);
        projectsManager.updateProjects();
      }

      // Mettre à jour les options du formulaire
      this.updateFormOptions();
    }
  }

  updateFormOptions() {
    const formOptions = {
      "form-select": document.querySelector('option[data-i18n="form-select"]'),
      "form-web": document.querySelector('option[data-i18n="form-web"]'),
      "form-mobile": document.querySelector('option[data-i18n="form-mobile"]'),
      "form-refonte": document.querySelector(
        'option[data-i18n="form-refonte"]',
      ),
      "form-both": document.querySelector('option[data-i18n="form-both"]'),
    };

    Object.entries(formOptions).forEach(([key, element]) => {
      if (element) element.textContent = this.translate(key);
    });
  }

  setupLanguageToggle() {
    const langButtons = document.querySelectorAll(".lang-btn");
    langButtons.forEach((btn) => {
      btn.addEventListener("click", () => {
        const lang = btn.getAttribute("data-lang");
        this.setLanguage(lang);

        // Mettre à jour l'état des boutons
        langButtons.forEach((b) => b.classList.remove("active"));
        btn.classList.add("active");
      });

      // Marquer le bouton actif au chargement
      if (btn.getAttribute("data-lang") === this.currentLanguage) {
        btn.classList.add("active");
      }
    });
  }
}

// Instantier le gestionnaire de traductions
const translationManager = new TranslationManager();
